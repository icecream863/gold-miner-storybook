async (page) => {
  try { await page.clock.resume(); } catch { /* 新浏览器无需恢复时钟。 */ }
  const base = 'https://icecream863.github.io/gold-miner-storybook/';
  const checks = [], errors = [], failed = [];
  const check = (name, pass, detail = '') => { checks.push({ name, pass: Boolean(pass), detail }); if (!pass) throw new Error(JSON.stringify({ checks, errors, failed })); };
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400 && r.url().startsWith(base)) failed.push({ url: r.url(), status: r.status() }); });
  await page.setViewportSize({ width: 1280, height: 800 });
  const response = await page.goto(base);
  await page.getByRole('button', { name: '开始寻金', exact: true }).waitFor();
  check('公网首页 HTTP 200', response.status() === 200);
  check('正式版本提供 session 入口', await page.getByRole('link', { name: 'AI 协作记录 ↗' }).isVisible());
  await page.getByRole('button', { name: '开始寻金', exact: true }).click();
  check('线上关卡目标与初始金钱', await page.locator('#goal').textContent() === '$650' && await page.locator('#money').textContent() === '$0');
  await page.keyboard.press('Space');
  await page.waitForTimeout(150);
  check('线上发射与回收状态有效', !(await page.locator('#status').textContent()).includes('看准方向'));
  await page.waitForTimeout(1500);
  check('线上回收后实际入账', await page.locator('#money').textContent() !== '$0');
  await page.keyboard.press('P');
  check('线上暂停界面', await page.getByRole('heading', { name: '矿灯还亮着' }).isVisible());
  const paused = await page.locator('#seconds').textContent();
  await page.waitForTimeout(1200);
  check('线上暂停冻结倒计时', await page.locator('#seconds').textContent() === paused);
  await page.screenshot({ path: 'output/playwright/online-paused.png', fullPage: true });
  await page.getByRole('button', { name: '继续寻金' }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'output/playwright/online-playing.png', fullPage: true });
  const records = await page.context().newPage();
  const recordResponse = await records.goto(base + 'session/');
  await records.getByRole('heading', { name: '黄金矿工 · 完整 AI 协作记录', exact: true }).waitFor();
  check('session 页面公开可读', recordResponse.status() === 200);
  check('session 下载链接齐全', await records.getByRole('link', { name: /下载结构化记录/ }).isVisible() && await records.getByRole('link', { name: /下载可读记录/ }).isVisible());
  const manifestResponse = await records.request.get(base + 'session/manifest.json');
  const manifest = await manifestResponse.json();
  const jsonlResponse = await records.request.get(base + 'session/session.jsonl');
  const lines = (await jsonlResponse.text()).trim().split('\n').map(l => JSON.parse(l));
  check('JSONL 可下载且条数与说明一致', jsonlResponse.status() === 200 && lines.length === manifest.records, `${lines.length} records`);
  check('记录包含原始测试要求与开发交流', lines.some(r => JSON.stringify(r).includes('网易互娱')) && manifest.assistantMessages > 10 && manifest.toolRecords > 30);
  await records.locator('#search').fill('窄屏');
  const shown = await records.locator('.entry:not(.hidden)').count();
  check('记录搜索有效', shown > 0 && shown < manifest.records);
  const video = await records.request.head(base + 'demo.webm');
  check('演示录像公开可访问', video.status() === 200 && Number(video.headers()['content-length']) > 1000000);
  const repository = await records.request.get('https://api.github.com/repos/icecream863/gold-miner-storybook');
  const repo = await repository.json();
  check('源码仓库公开可访问', repository.status() === 200 && repo.private === false);
  await records.close();
  await page.goto(base);
  await page.getByRole('button', { name: '开始寻金', exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(250);
  const bounds = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, width: innerWidth, button: document.querySelector('[data-action="start"]').getBoundingClientRect().toJSON() }));
  check('最终手机版无裁切或水平溢出', bounds.scroll <= bounds.width && bounds.button.x >= 0 && bounds.button.right <= bounds.width);
  await page.screenshot({ path: 'output/playwright/online-mobile.png', fullPage: true });
  check('线上脚本无异常、资源无 4xx', errors.length === 0 && failed.length === 0, JSON.stringify({ errors, failed }));
  await page.setViewportSize({ width: 1280, height: 800 });
  return { checks, total: checks.length, passed: checks.filter(c => c.pass).length, manifest, errors, failed };
}
